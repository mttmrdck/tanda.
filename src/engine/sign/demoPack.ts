import { CLIP_N, D } from '../constants';
import { bestSubWindow } from '../motion';
import { clipFeatures } from '../processor';
import { resampleClip } from '../resample';
import { simulateClip, type GestureName } from '../simulator';
import { encodeFloats, type Sign, type SignPack } from './pack';
import { heldWindow, MOVE_MS } from './window';

/**
 * The demo pack — made entirely by the simulator so the practice flow can be tried without a camera or a
 * signer. These are NOT real signs of any language; the UI always says "Demo only, not real signs".
 */
export const DEMO_PACK_ID = 'demo';
const RECORDED = '2026-11-17T00:00:00.000Z';
const TAKES = 5;

interface DemoDef {
  id: string;
  gesture: GestureName;
  gloss: string;
  gloss_ms: string;
  type: Sign['type'];
}

const DEFS: DemoDef[] = [
  { id: 'demo-wave', gesture: 'wave', gloss: 'Demo: wave', gloss_ms: 'Demo: lambai', type: 'dynamic' },
  { id: 'demo-mouth', gesture: 'handToMouth', gloss: 'Demo: hand to mouth', gloss_ms: 'Demo: tangan ke mulut', type: 'dynamic' },
  { id: 'demo-tap', gesture: 'tapTable', gloss: 'Demo: tap the table', gloss_ms: 'Demo: ketuk meja', type: 'dynamic' },
  { id: 'demo-arms-up', gesture: 'armsUp', gloss: 'Demo: arms up', gloss_ms: 'Demo: angkat tangan', type: 'dynamic' },
  { id: 'demo-open', gesture: 'shapeOpen', gloss: 'Demo: open hand', gloss_ms: 'Demo: tapak terbuka', type: 'static' },
  { id: 'demo-fist', gesture: 'shapeFist', gloss: 'Demo: fist', gloss_ms: 'Demo: genggam', type: 'static' },
  { id: 'demo-point', gesture: 'shapePoint', gloss: 'Demo: point', gloss_ms: 'Demo: tunjuk', type: 'static' },
  { id: 'demo-thumb', gesture: 'shapeThumb', gloss: 'Demo: thumb up', gloss_ms: 'Demo: ibu jari', type: 'static' },
];

/** Demo sign → the simulator gesture the demo performer plays for it. */
export const DEMO_GESTURE: Readonly<Record<string, GestureName>> = Object.fromEntries(DEFS.map((d) => [d.id, d.gesture]));

/** One synthetic take, processed exactly like a recorded one (2.5 s capture → window → resampled). */
export function demoTake(gesture: GestureName, seed: number, noise = 0.006, type: Sign['type'] = 'dynamic'): Float32Array | null {
  const feats = clipFeatures(simulateClip(gesture, { seed, noise, durationMs: 2500, dropout: 0.02 }));
  return resampleClip(type === 'static' ? heldWindow(feats) : bestSubWindow(feats, MOVE_MS), CLIP_N, D);
}

let cached: SignPack | null = null;

export function demoPack(): SignPack {
  if (cached) return cached;
  const signs: Sign[] = DEFS.map((def, i) => ({
    id: def.id,
    gloss: def.gloss,
    gloss_ms: def.gloss_ms,
    type: def.type,
    notes: 'Simulator movement. Not a real sign.',
    confusableWith: [],
    templates: Array.from({ length: TAKES }, (_, k) => demoTake(def.gesture, 7000 + i * 100 + k, 0.006, def.type))
      .filter((c): c is Float32Array => !!c)
      .map((c) => ({ n: CLIP_N, d: D, data: encodeFloats(c), recordedAt: RECORDED })),
  }));
  cached = {
    format: 'isyarat-signpack',
    schema: 1,
    id: DEMO_PACK_ID,
    language: 'DEMO',
    version: '1.0.0',
    title_en: 'Demo pack (simulator)',
    title_ms: 'Pek demo (simulator)',
    signs,
    signerCredits: [],
    reviewStatus: 'unreviewed',
    licence: 'Generated by the Isyarat simulator. Not real signs.',
    source: 'Isyarat synthetic performer',
    demo: true,
    builtIn: true,
    updatedAt: RECORDED,
  };
  return cached;
}
